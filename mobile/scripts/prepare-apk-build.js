#!/usr/bin/env node
/**
 * Prepare mobile app for EAS APK build (production AWS API).
 * Reads keys from mobile/.env and syncs into eas.json env + .env.production.
 * Run automatically via: npm run build:apk
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const easPath = path.join(root, "eas.json");
const envPath = path.join(root, ".env");
const envProdPath = path.join(root, ".env.production");
const awsConfigPath = path.join(root, "..", "config", "aws-production.json");
const apiUrlPath = path.join(root, "config", "apiUrl.json");

const REQUIRED = [
  "EXPO_PUBLIC_API_URL",
  "EXPO_PUBLIC_GOOGLE_MAPS_API_KEY",
  "EXPO_PUBLIC_RAZORPAY_KEY_ID",
];
const OPTIONAL = ["EXPO_PUBLIC_NATIVE_MAPS", "EXPO_PUBLIC_SKIP_SERVICEABILITY"];

function readDotEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i <= 0) continue;
    const key = t.slice(0, i).trim();
    let val = t.slice(i + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function writeDotEnv(filePath, vars) {
  const lines = [
    "# Auto-generated by scripts/prepare-apk-build.js — used by EAS production builds",
    "# Do not commit real secrets; copy from mobile/.env before npm run build:apk",
    "",
  ];
  for (const key of REQUIRED) {
    lines.push(`${key}=${vars[key] || ""}`);
  }
  for (const key of OPTIONAL) {
    if (vars[key] !== undefined) lines.push(`${key}=${vars[key]}`);
  }
  lines.push("");
  fs.writeFileSync(filePath, lines.join("\n"), "utf8");
}

function loadAwsApiUrl() {
  try {
    const aws = JSON.parse(fs.readFileSync(awsConfigPath, "utf8"));
    return aws.apiUrl || "";
  } catch (_) {
    return "";
  }
}

function syncApiUrlJson(apiUrl) {
  if (!apiUrl || !fs.existsSync(apiUrlPath)) return;
  const json = JSON.parse(fs.readFileSync(apiUrlPath, "utf8"));
  if (json.production !== apiUrl) {
    json.production = apiUrl;
    fs.writeFileSync(apiUrlPath, JSON.stringify(json, null, 2) + "\n", "utf8");
    console.log("Updated config/apiUrl.json → production:", apiUrl);
  }
}

function patchEasProfiles(eas, envVars) {
  const profiles = ["preview", "production"];
  for (const name of profiles) {
    if (!eas.build[name]) continue;
    eas.build[name].env = { ...envVars };
    eas.build[name].android = eas.build[name].android || {};
    eas.build[name].android.buildType = "apk";
    if (name === "production") {
      eas.build[name].distribution = eas.build[name].distribution || "internal";
      eas.build[name].environment = "production";
    }
  }
}

function main() {
  console.log("Preparing APK build configuration...\n");

  const localEnv = readDotEnv(envPath);
  const awsApiUrl = loadAwsApiUrl();
  const apiUrl = awsApiUrl || localEnv.EXPO_PUBLIC_API_URL || "";

  if (!apiUrl) {
    console.error("Missing production API URL.");
    console.error("Set config/aws-production.json apiUrl or EXPO_PUBLIC_API_URL in mobile/.env");
    process.exit(1);
  }

  const envVars = {
    EXPO_PUBLIC_API_URL: apiUrl,
    EXPO_PUBLIC_GOOGLE_MAPS_API_KEY: localEnv.EXPO_PUBLIC_GOOGLE_MAPS_API_KEY || "",
    EXPO_PUBLIC_RAZORPAY_KEY_ID: localEnv.EXPO_PUBLIC_RAZORPAY_KEY_ID || "",
    EXPO_PUBLIC_NATIVE_MAPS: "false",
    EXPO_PUBLIC_SKIP_SERVICEABILITY: localEnv.EXPO_PUBLIC_SKIP_SERVICEABILITY || "false",
  };

  const missing = REQUIRED.filter((k) => !envVars[k]);
  if (missing.length) {
    console.error("Missing required values in mobile/.env:");
    missing.forEach((k) => console.error("  -", k));
    console.error("\nAdd them to mobile/.env (same as local dev), then run again.");
    process.exit(1);
  }

  syncApiUrlJson(apiUrl);
  writeDotEnv(envProdPath, envVars);

  const eas = JSON.parse(fs.readFileSync(easPath, "utf8"));
  patchEasProfiles(eas, envVars);
  fs.writeFileSync(easPath, JSON.stringify(eas, null, 2) + "\n", "utf8");

  console.log("APK build env ready:");
  console.log("  EXPO_PUBLIC_API_URL            =", envVars.EXPO_PUBLIC_API_URL);
  console.log(
    "  EXPO_PUBLIC_GOOGLE_MAPS_API_KEY =",
    envVars.EXPO_PUBLIC_GOOGLE_MAPS_API_KEY.slice(0, 8) + "..."
  );
  console.log("  EXPO_PUBLIC_NATIVE_MAPS         =", envVars.EXPO_PUBLIC_NATIVE_MAPS);
  console.log("  EXPO_PUBLIC_SKIP_SERVICEABILITY =", envVars.EXPO_PUBLIC_SKIP_SERVICEABILITY);
  console.log("\nWrote mobile/.env.production (uploaded to EAS; not committed to git).");
  console.log("Updated eas.json production/preview env.");
  console.log("Next: eas build --platform android --profile production\n");
}

main();
